/**
 * Renders docs/REQUIREMENTS.md from the requirement catalogue and checks traceability:
 * every requirement must be referenced by at least one spec, and every reference
 * must point to a known requirement. Exits with code 1 otherwise, so CI catches
 * a requirement that was added without a test.
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { REQUIREMENTS, isRequirementId } from '../src/requirements';

const SPECS_DIR = 'tests/conformance/specs';
const OUTPUT_FILE = 'docs/REQUIREMENTS.md';
const REFERENCE_PATTERN = /requirement\('([A-Z]+-\d{3})'\)/g;

function collectReferences(): Map<string, Set<string>> {
  const references = new Map<string, Set<string>>();
  for (const file of readdirSync(SPECS_DIR).filter((name) => name.endsWith('.spec.ts'))) {
    const source = readFileSync(join(SPECS_DIR, file), 'utf8');
    for (const [, id] of source.matchAll(REFERENCE_PATTERN)) {
      if (id === undefined) continue;
      const files = references.get(id) ?? new Set<string>();
      files.add(file);
      references.set(id, files);
    }
  }
  return references;
}

function renderMarkdown(references: Map<string, Set<string>>): string {
  const rows = Object.entries(REQUIREMENTS).map(([id, { title, basis, risk, source }]) => {
    const specs = [...(references.get(id) ?? [])].map((file) => `\`${file}\``).join(', ');
    return `| ${id} | ${title} | ${basis} | ${risk} | ${source} | ${specs || '—'} |`;
  });

  return [
    '# Requirement catalogue',
    '',
    '> Generated by `npm run requirements:doc` from `tests/conformance/requirements.ts`. Do not edit by hand.',
    '',
    'Run one requirement with `npx playwright test --grep @<ID>`, or one basis with `--grep @standard`.',
    'Sources and the verification method are described in [SPEC-VERIFICATION.md](SPEC-VERIFICATION.md).',
    '',
    '| ID | Requirement | Basis | Risk if broken | Source | Tested in |',
    '| --- | --- | --- | --- | --- | --- |',
    ...rows,
    '',
  ].join('\n');
}

const references = collectReferences();
const untested = Object.keys(REQUIREMENTS).filter((id) => !references.has(id));
const unknown = [...references.keys()].filter((id) => !isRequirementId(id));

writeFileSync(OUTPUT_FILE, renderMarkdown(references));
console.info(`Wrote ${OUTPUT_FILE} (${Object.keys(REQUIREMENTS).length} requirements).`);

if (untested.length > 0 || unknown.length > 0) {
  if (untested.length > 0) console.error(`Requirements without a test: ${untested.join(', ')}`);
  if (unknown.length > 0)
    console.error(`Specs reference unknown requirements: ${unknown.join(', ')}`);
  process.exitCode = 1;
}
